#!/usr/bin/env python3
"""The Roku channel's translations.

The channel's own texts are written in English in the BrightScript code as L("English text") or
LF("English {name} text", { name: value }). The English text is the key. The Spanish, Italian and Portuguese
versions live in roku/i18n/strings.json, and this script compiles them into roku/components/lib/Strings.brs
(the file the channel loads). It also checks that:
  * every text used in the code has all three translations, with the same {placeholders},
  * no translation is left over after its text was removed from the code,
  * two texts do not differ only by capital letters (a BrightScript associative array ignores case),
  * L() and LF() are only given string literals (so this check can see them).

  python3 tool/roku_i18n.py            write Strings.brs
  python3 tool/roku_i18n.py --check    fail if anything is missing or Strings.brs is out of date (CI runs this)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / 'roku'
JSON_FILE = ROOT / 'i18n' / 'strings.json'
OUT_FILE = ROOT / 'components' / 'lib' / 'Strings.brs'
LANGS = ('es', 'it', 'pt')


def code_of(line: str, literals: list) -> str:
    """The code of one BrightScript line: comment dropped, each string literal replaced by "§n§"."""
    out, i, n = [], 0, len(line)
    while i < n:
        c = line[i]
        if c == '"':
            j, buf = i + 1, []
            while j < n:
                if line[j] == '"':
                    if line[j + 1:j + 2] == '"':
                        buf.append('"')
                        j += 2
                        continue
                    break
                buf.append(line[j])
                j += 1
            literals.append(''.join(buf))
            out.append('"§%d§"' % (len(literals) - 1))
            i = j + 1
        elif c == "'":
            break
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def used_keys(problems: list) -> dict:
    """Every literal passed to L() or LF() in the channel's code: key -> 'file:line' of the first use."""
    keys = {}
    for f in sorted(ROOT.glob('components/**/*.brs')) + sorted(ROOT.glob('source/**/*.brs')):
        if f == OUT_FILE:
            continue
        for n, raw in enumerate(f.read_text(encoding='utf-8').splitlines(), 1):
            if 'i18n:dynamic' in raw:
                continue
            lits = []
            code = code_of(raw, lits)
            if re.match(r'\s*(function|sub)\b', code, re.I):
                continue
            for m in re.finditer(r'(?<![\w.])LF?\(\s*(.?)', code):
                if m.group(1) != '"':
                    problems.append(f'{f.relative_to(ROOT.parent)}:{n}: L()/LF() needs a string literal, not {code[m.start():m.start() + 30]!r}')
            for m in re.finditer(r'(?<![\w.])LF?\(\s*"§(\d+)§"', code):
                keys.setdefault(lits[int(m.group(1))], f'{f.relative_to(ROOT.parent)}:{n}')
    return keys


def placeholders(s: str) -> list:
    return sorted(re.findall(r'\{([a-z]+)\}', s))


def brs_literal(s: str) -> str:
    return '"' + s.replace('"', '""') + '"'


def render(table: dict) -> str:
    lines = [
        "' GENERATED by tool/roku_i18n.py from roku/i18n/strings.json. Do not edit by hand.",
        "' The channel's own texts in Spanish, Italian and Portuguese. L(\"English text\") in Common.brs looks them up.",
        '',
        'function stringsFor(code as String) as Object',
        '    t = {}',
    ]
    for i, lang in enumerate(LANGS):
        lines.append(('    if' if i == 0 else '    else if') + f' code = "{lang}" then')
        for key in table:
            lines.append(f'        t[{brs_literal(key)}] = {brs_literal(table[key][lang])}')
    lines += ['    end if', '    return t', 'end function', '']
    return '\n'.join(lines)


def main() -> int:
    check = '--check' in sys.argv
    table = json.loads(JSON_FILE.read_text(encoding='utf-8'))
    problems = []
    used = used_keys(problems)

    for key, where in sorted(used.items()):
        if key not in table:
            problems.append(f'{where}: no translation for "{key}" (add it to roku/i18n/strings.json)')
    for key in sorted(table):
        if key not in used:
            problems.append(f'roku/i18n/strings.json: "{key}" is not used in the code any more (remove it)')
        for lang in LANGS:
            v = table[key].get(lang)
            if not isinstance(v, str) or not v.strip():
                problems.append(f'roku/i18n/strings.json: "{key}" has no {lang} text')
            elif placeholders(v) != placeholders(key):
                problems.append(f'roku/i18n/strings.json: "{key}" in {lang} has placeholders {placeholders(v)}, the English has {placeholders(key)}')
    seen = {}
    for key in table:
        low = key.lower()
        if low in seen:
            problems.append(f'roku/i18n/strings.json: "{key}" and "{seen[low]}" differ only by capital letters (BrightScript ignores case in keys)')
        seen[low] = key
    for key in used:
        if re.search(r'\{[^}]*[^a-z}][^}]*\}', key):
            problems.append(f'{used[key]}: placeholders in "{key}" must be lower-case letters only')

    text = render(table)
    if check:
        if not OUT_FILE.exists() or OUT_FILE.read_text(encoding='utf-8') != text:
            problems.append('roku/components/lib/Strings.brs is out of date: run python3 tool/roku_i18n.py')
    elif not problems:
        OUT_FILE.write_text(text, encoding='utf-8')
        print(f'wrote {OUT_FILE.relative_to(ROOT.parent)}')

    for p in problems:
        print(p)
    print(f'{len(used)} texts used, {len(table)} translated, {len(problems)} problems')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
